const TABLES: Record<Lang, Record<Key, string>> = { en, id };

export type TFn = (key: Key, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): TFn {
	const table = TABLES[lang];
	return (key, vars) => (table[key] ?? en[key]).replace(/\{(\w+)\}/g, (m, name: string) => (vars && name in vars ? String(vars[name]) : m));
}
